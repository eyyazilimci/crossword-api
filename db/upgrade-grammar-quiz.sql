-- Adds the grammar quiz tables to a database created from an earlier schema.sql.
-- New databases only need schema.sql. Same as: dotnet ef database update

START TRANSACTION;
CREATE TABLE quiz_questions (
    id integer GENERATED BY DEFAULT AS IDENTITY,
    key character varying(40) NOT NULL,
    topic character varying(40) NOT NULL,
    level character varying(4) NOT NULL,
    prompt character varying(500) NOT NULL,
    options text[] NOT NULL,
    correct_index integer NOT NULL,
    explanation character varying(1000) NOT NULL,
    is_active boolean NOT NULL,
    created_at timestamp with time zone NOT NULL,
    reported_at timestamp with time zone,
    CONSTRAINT pk_quiz_questions PRIMARY KEY (id)
);

CREATE TABLE quiz_sessions (
    id uuid NOT NULL,
    kind character varying(16) NOT NULL,
    daily_date date,
    topic character varying(40),
    question_ids integer[] NOT NULL,
    choices integer[] NOT NULL,
    status character varying(16) NOT NULL,
    correct_count integer NOT NULL,
    started_at timestamp with time zone NOT NULL,
    updated_at timestamp with time zone NOT NULL,
    completed_at timestamp with time zone,
    CONSTRAINT pk_quiz_sessions PRIMARY KEY (id)
);

CREATE TABLE question_progress (
    question_id integer NOT NULL,
    seen_count integer NOT NULL,
    correct_count integer NOT NULL,
    wrong_count integer NOT NULL,
    last_correct boolean NOT NULL,
    last_answered_at timestamp with time zone NOT NULL,
    last_answered_on date NOT NULL,
    CONSTRAINT pk_question_progress PRIMARY KEY (question_id),
    CONSTRAINT fk_question_progress_quiz_questions_question_id FOREIGN KEY (question_id) REFERENCES quiz_questions (id) ON DELETE CASCADE
);

CREATE UNIQUE INDEX ix_quiz_questions_key ON quiz_questions (key);

CREATE INDEX ix_quiz_questions_topic ON quiz_questions (topic);

CREATE UNIQUE INDEX ix_quiz_sessions_daily_date ON quiz_sessions (daily_date) WHERE daily_date IS NOT NULL;

INSERT INTO "__EFMigrationsHistory" (migration_id, product_version)
VALUES ('20261024190949_AddGrammarQuiz', '10.0.13');

COMMIT;

