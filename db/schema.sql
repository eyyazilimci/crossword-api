CREATE TABLE player_profiles (
    id integer NOT NULL,
    total_xp integer NOT NULL,
    puzzles_completed integer NOT NULL,
    current_streak integer NOT NULL,
    longest_streak integer NOT NULL,
    last_played_on date,
    CONSTRAINT pk_player_profiles PRIMARY KEY (id)
);

CREATE TABLE puzzles (
    id uuid NOT NULL,
    mode character varying(16) NOT NULL,
    difficulty character varying(16) NOT NULL,
    width integer NOT NULL,
    height integer NOT NULL,
    seed integer NOT NULL,
    daily_date date,
    created_at timestamp with time zone NOT NULL,
    CONSTRAINT pk_puzzles PRIMARY KEY (id)
);

CREATE TABLE unlocked_achievements (
    id integer GENERATED BY DEFAULT AS IDENTITY,
    code character varying(40) NOT NULL,
    unlocked_at timestamp with time zone NOT NULL,
    CONSTRAINT pk_unlocked_achievements PRIMARY KEY (id)
);

CREATE TABLE words (
    id integer GENERATED BY DEFAULT AS IDENTITY,
    english character varying(40) NOT NULL,
    turkish character varying(40) NOT NULL,
    part_of_speech character varying(16) NOT NULL,
    level character varying(4) NOT NULL,
    frequency_rank integer NOT NULL,
    CONSTRAINT pk_words PRIMARY KEY (id)
);

CREATE TABLE game_sessions (
    id uuid NOT NULL,
    puzzle_id uuid NOT NULL,
    status character varying(16) NOT NULL,
    letters text NOT NULL,
    revealed_mask text NOT NULL,
    mistake_mask text NOT NULL,
    elapsed_seconds integer NOT NULL,
    checks_used integer NOT NULL,
    reveals_used integer NOT NULL,
    failed_submits integer NOT NULL,
    score integer NOT NULL,
    xp_earned integer NOT NULL,
    started_at timestamp with time zone NOT NULL,
    updated_at timestamp with time zone NOT NULL,
    completed_at timestamp with time zone,
    CONSTRAINT pk_game_sessions PRIMARY KEY (id),
    CONSTRAINT fk_game_sessions_puzzles_puzzle_id FOREIGN KEY (puzzle_id) REFERENCES puzzles (id) ON DELETE CASCADE
);

CREATE TABLE puzzle_entries (
    id integer GENERATED BY DEFAULT AS IDENTITY,
    puzzle_id uuid NOT NULL,
    word_id integer NOT NULL,
    number integer NOT NULL,
    orientation character varying(8) NOT NULL,
    row_index integer NOT NULL,
    column_index integer NOT NULL,
    answer character varying(40) NOT NULL,
    clue character varying(40) NOT NULL,
    CONSTRAINT pk_puzzle_entries PRIMARY KEY (id),
    CONSTRAINT fk_puzzle_entries_puzzles_puzzle_id FOREIGN KEY (puzzle_id) REFERENCES puzzles (id) ON DELETE CASCADE,
    CONSTRAINT fk_puzzle_entries_words_word_id FOREIGN KEY (word_id) REFERENCES words (id) ON DELETE RESTRICT
);

CREATE TABLE word_masteries (
    word_id integer NOT NULL,
    mode character varying(16) NOT NULL,
    correct_count integer NOT NULL,
    wrong_count integer NOT NULL,
    last_seen_at timestamp with time zone NOT NULL,
    CONSTRAINT pk_word_masteries PRIMARY KEY (word_id, mode),
    CONSTRAINT fk_word_masteries_words_word_id FOREIGN KEY (word_id) REFERENCES words (id) ON DELETE CASCADE
);

